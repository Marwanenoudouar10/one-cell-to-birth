"""Build a one-page "chapter pack" per long-film chapter, so a builder/polisher
reads ~1 page of exactly what it needs instead of ~2,000 lines of briefs.
usage: python3 scripts/make_packs.py C09 C10 ...   (default: C08-C16)
-> briefs/long/packs/<id>.md"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
B = os.path.join(ROOT, "briefs", "long")

# which facts (facts.md "### N.") and kits each chapter needs
FACTS = {"C08": [10, 11], "C09": [11, 12], "C10": [13, 14], "C11": [15], "C12": [16, 17],
         "C13": [18], "C14": [19, 20], "C15": [21], "C16": [22, 23, 24, 25]}
KITS = {"C08": ["embryo", "womb"], "C09": ["embryo", "fetus", "womb"]}


def sections(text, pat):
    idx = [(m.start(), m.group(1)) for m in re.finditer(pat, text, re.M)]
    out = {}
    for i, (pos, key) in enumerate(idx):
        end = idx[i + 1][0] if i + 1 < len(idx) else len(text)
        out[key] = text[pos:end].strip()
    return out


def end_state(sec):
    m = re.search(r"\*\*END[^*]*\*\*.*?(?=\n- \*\*|\Z)", sec, re.S)
    return m.group(0).strip() if m else "(see storyboard)"


def live_end(cid):
    """The finished upstream chapter's real END: briefs/long/ends/<id>.md (from its polish
    review), else the END block in its beats.ts."""
    e = os.path.join(B, "ends", f"{cid}.md")
    if os.path.exists(e):
        return open(e).read()
    p = os.path.join(ROOT, "src", "long", "chapters", cid, "beats.ts")
    if not os.path.exists(p):
        return "(no beats.ts yet)"
    lines = open(p).read().splitlines()
    idx = [i for i, l in enumerate(lines) if re.search(r"END\b", l) and ("contract" in l.lower() or "C0" in l or "C1" in l)]
    start = idx[0] if idx else max(0, len(lines) - 60)
    return "\n".join(lines[start:start + 90])


def main(ids):
    sb = open(os.path.join(B, "storyboard.md")).read()
    chap = sections(sb, r"^## (C\d\d) ·")
    facts = sections(open(os.path.join(B, "facts.md")).read(), r"^### (\d+)\.")
    kits = sections(open(os.path.join(B, "foundations.md")).read(), r"^## (fetus|embryo|womb|framework)$")
    vo = sections(open(os.path.join(B, "vo-words.md")).read(), r"^## (C\d\d)$")
    order = sorted(chap)
    os.makedirs(os.path.join(B, "packs"), exist_ok=True)
    for cid in ids:
        i = order.index(cid)
        prev, nxt = (order[i - 1] if i > 0 else None), (order[i + 1] if i + 1 < len(order) else None)
        parts = [f"# Chapter pack {cid} (generated by scripts/make_packs.py — read this INSTEAD of the full briefs)\n",
                 "Rules: CLAUDE.md (read it). Everything else you need is below; open the full briefs only if something here is unclear.\n",
                 "## Your storyboard section\n", chap[cid], "\n"]
        if prev:
            parts += [f"## Previous chapter {prev}: its END (your frame 0 must match it; the orchestrator does one final pixel pass over all joins, so match the numbers, don't pixel-chase)\n",
                      "Storyboard plan (may be OUTDATED):", end_state(chap[prev]), "\nACTUAL END of the finished chapter (this wins; code in src/long/chapters/" + prev + "/):\n", live_end(prev), "\n"]
        if nxt:
            parts += [f"## Next chapter {nxt}: how it starts (your END must hand over to this)\n", chap[nxt][:1800], "\n"]
        parts += ["## Real voice word timings (chapter-local seconds, measured from the audio — trust these)\n",
                  vo.get(cid, "(missing: ask the orchestrator)"), "\n"]
        parts += ["## Facts for this chapter (verified)\n"] + [facts[str(n)] for n in FACTS.get(cid, []) if str(n) in facts] + ["\n"]
        for k in KITS.get(cid, ["fetus", "womb"]):
            parts += [f"## Kit API: {k}\n", kits.get(k, "")[:6000], "\n"]
        open(os.path.join(B, "packs", f"{cid}.md"), "w").write("\n".join(parts))
        print(cid, len("\n".join(parts).splitlines()), "lines")


if __name__ == "__main__":
    main(sys.argv[1:] or [f"C{n:02d}" for n in range(8, 17)])
