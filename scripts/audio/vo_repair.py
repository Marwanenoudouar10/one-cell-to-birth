"""Repair the long-film VO clips (public/vo/long/Cxx.wav) and their word timings.

long_vo.py cut the chapters where raw whisper timestamps (0.3-0.5 s drift) said, so some
clips started or ended inside a neighbour chapter's words. This script KEEPS each
chapter's source->local mapping (local = take time + shift; the shift is recovered by
finding the current clip bit-exactly inside its take) and never touches chapters.ts.
  1. Speech span of every chapter in its take: the caption words are matched to whisper
     DTW words of the whole take; each chapter boundary is the longest silence (< -70 dB,
     >= 0.1 s) between the last word of one chapter and the first of the next.
  2. Cuts: the lowest-energy 5 ms frame of the silence before / after the span (head
     0.03-0.30 s before the first sound, tail 0.06-0.30 s after the last one), never
     into the neighbour's speech; bit-exact samples, 12 ms linear fade-in, 55 ms fade-out.
     clipAt = new head cut + shift, so every word stays where it was heard in the film.
  3. Word onsets: measured inside each final clip (vo_onsets.py: whisper DTW guide
     snapped to the 10 ms energy envelope). Line start = first onset, line end = last
     sound before the next line's first onset (or the clip end).
  4. Writes src/long/data/voTiming.ts (same format and header) and
     briefs/long/vo-words.md, and prints the report: cuts, what whisper hears at the
     head and tail of each new clip, level before/after the speech, max word move,
     global gap to the next chapter's speech, overflow past the chapter's window.
usage: nice -n 10 python3 scripts/audio/vo_repair.py [--dry]   (--dry: report only)
Rerunnable: the mapping is re-read from the current clips, so a rerun gives the same result.
"""
import array
import json
import os
import shutil
import sys
import tempfile
import wave

sys.path.insert(0, os.path.dirname(__file__))
import vo_onsets as O  # noqa: E402
from long_vo import INBOX, ROOT, chapters, parse_lines  # noqa: E402
from util import SR  # noqa: E402

HOP, SIL = O.HOP, O.SIL
HEAD, TAIL = (0.03, 0.30), (0.06, 0.30)  # cut search: before first sound / after last sound
FADE_IN, FADE_OUT = 0.012, 0.055
FPS, TRANS = 30, 15  # chapters.ts: 30 fps; fade/focus transitions overlap 15 frames
VO_DIR = os.path.join(ROOT, "public", "vo", "long")
TS_PATH = os.path.join(ROOT, "src", "long", "data", "voTiming.ts")
MD_PATH = os.path.join(ROOT, "briefs", "long", "vo-words.md")
HEADER = (
    "// GENERATED by scripts/audio/long_vo.py from the ElevenLabs takes. Do not edit.\n"
    "// Chapter-LOCAL seconds. clipAt = where the chapter's clip starts; per line: start/end of\n"
    "// speech and each word's start (same word order as the caption text in lines.ts).\n"
    "export type VoLine = { start: number; end: number; words: number[] };\n"
    "export const VO_TIMING: Record<string, { src: string; clipAt: number; lines: VoLine[] }> = ")


def pcm(path):
    w = wave.open(path)
    assert (w.getnchannels(), w.getsampwidth(), w.getframerate()) == (1, 2, SR), path
    a = array.array("h")
    a.frombytes(w.readframes(w.getnframes()))
    return a


def words_of(lines, cid):
    return [w for ln in lines[cid] for w in ln["text"].split(" ")]


def silences(env, min_len=0.1):
    """All runs of frames below SIL lasting >= min_len: [(first, after_last)] frames."""
    runs, i = [], 1
    while i < len(env):
        if env[i] < SIL:
            j = i
            while j < len(env) and env[j] < SIL:
                j += 1
            if (j - i) * HOP >= min_len:
                runs.append((i, j))
            i = j
        else:
            i += 1
    return runs


def lowest(env, t0, t1):
    """Centre time of the lowest-energy frame (3-frame mean) in [t0, t1], or None."""
    i0, i1 = max(0, round((t0 - 0.005) / HOP)), min(len(env) - 1, round((t1 - 0.005) / HOP))
    sm = lambda i: sum(env[max(0, i - 1):i + 2]) / len(env[max(0, i - 1):i + 2])  # noqa: E731
    return min(range(i0, i1 + 1), key=sm) * HOP + 0.005 if i1 >= i0 else None


def spans(env, heard, items):
    """Speech span (first sound, end of last sound) of each chapter in take seconds."""
    g = O.guides([w for _, ws in items for w in ws], heard)
    edges, k = [], 0
    for _, ws in items:
        edges.append((g[k], g[k + len(ws) - 1]))
        k += len(ws)
    runs = silences(env)
    on = [next(i for i, x in enumerate(env) if x >= SIL) * HOP]
    ends = []
    for (_, last), (nxt, _) in zip(edges, edges[1:]):
        lo, hi = round(last / HOP), round((nxt + 0.15) / HOP)
        s, e = max((r for r in runs if r[1] > lo and r[0] < hi), key=lambda r: r[1] - r[0])
        ends.append((s + 1) * HOP)  # end of the last loud 10 ms frame
        on.append(e * HOP)
    ends.append((max(i for i, x in enumerate(env) if x >= SIL) + 2) * HOP)
    return list(zip(on, ends))


def locate(cur, take):
    """Start (s) of clip bytes `cur` inside the take bytes (bit-exact middle chunk)."""
    mid = (len(cur) // 4) * 2
    pos = take.find(cur[mid:mid + 4000])
    while pos >= 0 and pos % 2:
        pos = take.find(cur[mid:mid + 4000], pos + 1)
    return None if pos < 0 else (pos - mid) / 2 / SR


def write_clip(path, take, c0, c1):
    s = array.array("h", take[round(c0 * SR):round(c1 * SR)])
    nin, nout = round(FADE_IN * SR), round(FADE_OUT * SR)
    for k in range(nin):
        s[k] = int(s[k] * k / nin)
    for k in range(nout):
        s[-1 - k] = int(s[-1 - k] * k / nout)
    w = wave.open(path, "wb")
    w.setnchannels(1)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes(s.tobytes())
    w.close()
    return round(c0 * SR) / SR, round(c1 * SR) / SR


def plan_cuts(chs, lines, old, tmp):
    """{cid: (take pcm, head, tail, shift, old head, old length)} in take seconds."""
    plan = {}
    for take in ("vo-intro", "vo-main"):
        path = os.path.join(INBOX, f"{take}-norm.wav")
        tp, env = pcm(path), O.envelope(path)
        ids = [c["id"] for c in chs if (c["id"] == "C00") == (take == "vo-intro") and c["id"] in lines]
        sp = spans(env, O.whisper(path, tmp), [(cid, words_of(lines, cid)) for cid in ids])
        raw, total = tp.tobytes(), len(tp) / SR
        for k, cid in enumerate(ids):
            cur = pcm(os.path.join(VO_DIR, f"{cid}.wav")).tobytes()
            c0_old = locate(cur, raw)
            assert c0_old is not None, f"{cid}: clip not found in {take} (clips regenerated? rerun long_vo.py)"
            shift = old[cid]["clipAt"] - c0_old
            on, end = sp[k]
            prev_end = sp[k - 1][1] if k else 0.0
            nxt_on = sp[k + 1][0] if k + 1 < len(sp) else 1e9
            h = lowest(env, max(on - HEAD[1], prev_end + TAIL[0], 0.0, -shift), on - HEAD[0])
            t = lowest(env, end + TAIL[0], min(end + TAIL[1], nxt_on - HEAD[0], total - 0.006))
            plan[cid] = (tp, 0.0 if h is None else h, total if t is None else t, shift, c0_old, len(cur) / 2 / SR)
    return plan


def measure(cid, clip, at, lines, tmp):
    """voTiming entry for one final clip + (whisper words, methods, envelope)."""
    on, how, heard, env = O.onsets(clip, words_of(lines, cid), tmp)
    lns, k = [], 0
    for ln in lines[cid]:
        n = len(ln["text"].split(" "))
        nxt = on[k + n] - 0.02 if k + n < len(on) else len(env) * HOP
        lns.append({"start": round(at + on[k], 3), "end": round(at + O.last_sound(env, on[k + n - 1], nxt), 3),
                    "words": [round(at + w, 3) for w in on[k:k + n]]})
        k += n
    return {"src": f"vo/long/{cid}.wav", "clipAt": at, "lines": lns}, heard, how, env


def main(dry):
    lines, chs = parse_lines(), chapters()
    src = open(TS_PATH).read()
    old = json.loads(src[src.index("> = {") + 4:src.rindex(";")])
    start, t = {}, 0  # LONG_START in frames, as chapters.ts computes it
    for k, c in enumerate(chs):
        t -= TRANS if k > 0 and c["tr"] != "cut" else 0
        start[c["id"]] = t
        t += round(c["dur"] * FPS)
    tmp = tempfile.mkdtemp()
    out, rows = {}, []
    for cid, (tp, h, tl, shift, c0_old, len_old) in plan_cuts(chs, lines, old, tmp).items():
        clip = os.path.join(tmp if dry else VO_DIR, f"{cid}.wav")
        c0, c1 = write_clip(clip, tp, h, tl)
        out[cid], heard, how, env = measure(cid, clip, round(c0 + shift, 3), lines, tmp)
        v = out[cid]
        head_db = max(env[:max(1, round((v["lines"][0]["start"] - v["clipAt"] - 0.03) / HOP))])
        tail_db = max(env[round((v["lines"][-1]["end"] - v["clipAt"] + 0.03) / HOP):] or [-120.0])
        move = max(abs(a - b) for lo, ln in zip(old[cid]["lines"], v["lines"]) for a, b in zip(lo["words"], ln["words"]))
        rows.append((cid, c0_old, len_old, c0, c1, heard or [(0, "?")], how, head_db, tail_db, move))
    print("cid  clipAt old->new | take cut old -> new | whisper first..last | dB before/after speech | onset kinds | max word move")
    for cid, c0o, lo_, c0, c1, heard, how, hd, td, mv in rows:
        ws = words_of(lines, cid)
        ok = O.norm(heard[0][1]) == O.norm(ws[0]) and O.norm(heard[-1][1]) == O.norm(ws[-1])
        print(f"{cid} {old[cid]['clipAt']:6.3f}->{out[cid]['clipAt']:6.3f} | {c0o:7.3f}-{c0o + lo_:7.3f} -> "
              f"{c0:7.3f}-{c1:7.3f} | {heard[0][1]}..{heard[-1][1]} {'OK' if ok else 'MISMATCH'} "
              f"({len(heard)}/{len(ws)}) | {hd:4.0f}/{td:4.0f} | {''.join(how)} | {mv:4.2f}s")
    print("\ncid  speech local start-end / window | global start-end | gap to next chapter's speech")
    ids = [c["id"] for c in chs if c["id"] in out]
    for k, cid in enumerate(ids):
        c = next(c for c in chs if c["id"] == cid)
        g0, (s0, s1) = start[cid] / FPS, (out[cid]["lines"][0]["start"], out[cid]["lines"][-1]["end"])
        nx = ids[k + 1] if k + 1 < len(ids) else None
        gap = start[nx] / FPS + out[nx]["lines"][0]["start"] - (g0 + s1) if nx else None
        flag = (f"  OVERFLOW: speech ends {s1 - c['dur']:.3f} s after the window" if s1 > c["dur"] else "") + \
               ("  GAP < 0.25 s" if gap is not None and gap < 0.25 else "")
        print(f"{cid} {s0:6.3f}-{s1:6.3f} / {c['dur']:4.1f} | {g0 + s0:7.3f}-{g0 + s1:7.3f} | "
              f"{'-' if gap is None else f'{gap:.3f}'}{flag}")
    if not dry:
        write_outputs(out, lines)
    shutil.rmtree(tmp)
    return out


def write_outputs(out, lines):
    with open(TS_PATH, "w") as f:
        f.write(HEADER + json.dumps(out, indent=1) + ";\n")
    md = ["# Real voice timings (chapter-LOCAL seconds) — generated from the ElevenLabs takes", "",
          "Use these to time your beats.ts: each `// sync: \"<word>\"` beat should land on (or just before) the word below.",
          "Onsets are measured in each chapter's own clip by scripts/audio/vo_repair.py (whisper DTW guide snapped "
          "to the 10 ms energy envelope, ~25 ms typical error); a line ends at its last word's last sound."]
    for cid, v in out.items():
        md += ["", f"## {cid}"]
        for i, (ln, vl) in enumerate(zip(lines[cid], v["lines"])):
            ws = "  ".join(f"{w} {t:.2f}" for w, t in zip(ln["text"].split(" "), vl["words"]))
            md.append(f"- line {i + 1} ({vl['start']:.2f}–{vl['end']:.2f}s): {ws}")
    with open(MD_PATH, "w") as f:
        f.write("\n".join(md) + "\n")


if __name__ == "__main__":
    main("--dry" in sys.argv)
