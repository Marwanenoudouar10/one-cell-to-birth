"""Voiceover: normalise, find phrases, cut one clip per line, write timing TS."""
import json
import os

from util import duration, ff, loudnorm_linear, silences

# Edit decision list: global time (s) where each line's first word starts,
# and the phrases (separated by pauses in the take) that make up the line.
LINES = [
    ("l1", 0.50, ["It starts with a race."]),
    ("l2", 2.40, ["Millions run.", "Only one wins."]),
    ("l3", 6.45, ["One cell becomes two…", "four…", "hundreds."]),
    ("l4", 11.60, ["Week six:", "a tiny heart starts to beat."]),
    ("l5", 16.55, ["Week twelve:", "fingers, toes, a face."]),
    ("l6", 20.25, ["Week twenty:", "the first kick."]),
    ("l7", 23.60, ["Week forty:", "one cell has become a whole new human."]),
    ("l8", 28.00, ["Hello, world."]),
]
PRE, POST = 0.10, 0.18  # breathing room kept around each clip


def phrases(path):
    total = duration(path)
    sil = [(s, e if e is not None else total) for s, e in silences(path)]
    segs, t = [], 0.0
    for s, e in sil:
        if s > t + 0.001:
            segs.append([t, s])
        t = e
    if t < total - 0.02:
        segs.append([t, total])
    # merge blips (< 150 ms: a lone "a", a released "k") into the nearer neighbour
    i = 0
    while i < len(segs):
        a, b = segs[i]
        if b - a < 0.15 and len(segs) > 1:
            gap_prev = a - segs[i - 1][1] if i > 0 else 1e9
            gap_next = segs[i + 1][0] - b if i + 1 < len(segs) else 1e9
            if gap_prev <= gap_next:
                segs[i - 1][1] = b
            else:
                segs[i + 1][0] = a
            segs.pop(i)
            continue
        i += 1
    return segs, total


def word_starts(text, a, b):
    """Spread words across [a, b] by length (good enough inside one phrase)."""
    words = text.split(" ")
    weights = [len(w) + 2 for w in words]
    tot, acc, out = sum(weights), 0, []
    for wgt in weights:
        out.append(a + (b - a) * acc / tot)
        acc += wgt
    return out


def build(src, root):
    norm = os.path.join(root, "inbox", "vo-norm.wav")
    loudnorm_linear(src, norm, target=-16.0)
    segs, total = phrases(norm)
    want = sum(len(p) for _, _, p in LINES)
    assert len(segs) == want, f"found {len(segs)} phrases, expected {want}: {segs}"

    timing, k = {}, 0
    for idx, (lid, at, parts) in enumerate(LINES):
        ps = segs[k:k + len(parts)]
        k += len(parts)
        prev_end = segs[k - len(parts) - 1][1] if k - len(parts) > 0 else 0.0
        next_start = segs[k][0] if k < len(segs) else total
        c0 = max(prev_end + (ps[0][0] - prev_end) / 2, ps[0][0] - PRE)
        c1 = min(ps[-1][1] + (next_start - ps[-1][1]) / 2, ps[-1][1] + POST)
        shift = at - ps[0][0]  # rel -> global
        out = os.path.join(root, "public", "vo", f"{lid}.wav")
        ff("-i", norm, "-af",
           f"atrim={c0:.3f}:{c1:.3f},asetpts=PTS-STARTPTS,"
           f"afade=t=in:d=0.012,afade=t=out:st={c1 - c0 - 0.05:.3f}:d=0.05",
           "-c:a", "pcm_s16le", out)
        words = []
        for text, (a, b) in zip(parts, ps):
            words += [round(t + shift, 3) for t in word_starts(text, a, b)]
        timing[lid] = {
            "src": f"vo/{lid}.wav",
            "clipAt": round(c0 + shift, 3),
            "start": round(ps[0][0] + shift, 3),
            "end": round(ps[-1][1] + shift, 3),
            "words": words,
        }
    ts = os.path.join(root, "src", "theme", "voTiming.ts")
    with open(ts, "w") as f:
        f.write("// GENERATED by scripts/audio/build.py from the voiceover take. Do not edit.\n")
        f.write("// Global seconds. start/end = first/last spoken sound; words = each word's start.\n")
        f.write("export const VO_TIMING: Record<string, { src: string; clipAt: number; start: number; end: number; words: number[] }> = ")
        f.write(json.dumps(timing, indent=2, ensure_ascii=False) + ";\n")
    return timing
