#!/bin/bash
# (Re)generate the isolated preview entry src/long/preview/<id>.ts for one chapter.
# It imports ONLY that chapter (or uses the placeholder if the chapter folder has no
# index.tsx yet), so another chapter's broken files can never break this preview.
# usage: scripts/long-entry.sh C05      (prints the entry path)
set -e
cd "$(dirname "$0")/.."
ID=$1
[[ "$ID" =~ ^[A-Za-z][A-Za-z0-9_]*$ ]] || { echo "usage: $0 <ChapterId, e.g. C05>" >&2; exit 1; }
grep -q "id: \"$ID\"" src/long/chapters.ts || { echo "unknown chapter $ID (not in src/long/chapters.ts)" >&2; exit 1; }
mkdir -p src/long/preview
ENTRY=src/long/preview/$ID.ts
if [ -f "src/long/chapters/$ID/index.tsx" ] || [ -f "src/long/chapters/$ID/index.ts" ]; then
  cat > "$ENTRY" <<TS
// GENERATED by scripts/long-entry.sh. Do not edit; re-run the script instead.
import { registerRoot } from "remotion";
import { $ID } from "../chapters/$ID";
import { makeChapterRoot } from "./makeChapterRoot";

registerRoot(makeChapterRoot("$ID", $ID));
TS
else
  cat > "$ENTRY" <<TS
// GENERATED by scripts/long-entry.sh. Do not edit; re-run the script instead.
// src/long/chapters/$ID/index.tsx does not exist yet -> placeholder card.
import { registerRoot } from "remotion";
import { makeChapterRoot } from "./makeChapterRoot";

registerRoot(makeChapterRoot("$ID"));
TS
fi
echo "$ENTRY"
